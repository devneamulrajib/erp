/* global __dirname */
// Expo config plugin: Android network security config with a bundled root CA.
//
// Why: api.erp.mwm247.com chains to "SSL.com TLS RSA Root CA 2022", which is missing
// from the system trust store of older Android versions (OnePlus 8 / Android <= 13),
// so OkHttp (React Native fetch/axios) fails the TLS handshake. Chrome ships its own
// store, which is why the site still opens in the browser.
//
// What: writes res/xml/network_security_config.xml + res/raw/sslcom_tls_rsa_root_ca_2022.pem
// and points android:networkSecurityConfig at it. Trust = system CAs + this one root
// (user-installed CAs are NOT trusted). Cleartext stays off in release builds unless
// APP_VARIANT=development; debug builds (Metro dev server) permit it.
// Runs on every `expo prebuild` (incl. --clean), so it survives regeneration of android/.
//
// Root verified 2026-11-18: SHA-256 8F:AF:7D:2E:2C:B4:70:9B:B8:E0:B3:36:66:BF:75:A5:
// DD:45:B5:DE:48:0F:8E:A8:D4:BF:E6:BE:BC:17:F2:ED (ssl.com/repository, CCADB, Chrome Root Store).
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const CERT_NAME = 'sslcom_tls_rsa_root_ca_2022';
const CERT_SRC = path.join(__dirname, 'certs', `${CERT_NAME}.pem`);

function buildXml(allowCleartext) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withNetworkSecurityConfig.js. Do not edit; change the plugin. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="${allowCleartext ? 'true' : 'false'}">
        <trust-anchors>
            <certificates src="system" />
            <!-- SSL.com TLS RSA Root CA 2022 (missing on older Android trust stores) -->
            <certificates src="@raw/${CERT_NAME}" />
        </trust-anchors>
    </base-config>
</network-security-config>
`;
}

module.exports = function withNetworkSecurityConfig(config, { allowCleartext = false } = {}) {
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const res = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res');
      fs.mkdirSync(path.join(res, 'xml'), { recursive: true });
      fs.mkdirSync(path.join(res, 'raw'), { recursive: true });
      fs.writeFileSync(path.join(res, 'xml', 'network_security_config.xml'), buildXml(allowCleartext));
      fs.copyFileSync(CERT_SRC, path.join(res, 'raw', `${CERT_NAME}.pem`));
      // Debug builds load JS from the Metro dev server over plain http, so their
      // variant-specific copy permits cleartext. Release builds only use src/main.
      for (const variant of ['debug', 'debugOptimized']) {
        const dir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', variant, 'res', 'xml');
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(path.join(dir, 'network_security_config.xml'), buildXml(true));
      }
      return cfg;
    },
  ]);
  return withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0];
    if (app) {
      app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
      // With a network security config the manifest flag is ignored on API 24+,
      // but keep it consistent for clarity.
      app.$['android:usesCleartextTraffic'] = allowCleartext ? 'true' : 'false';
    }
    return cfg;
  });
};
